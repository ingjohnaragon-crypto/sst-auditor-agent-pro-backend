#!/bin/sh
set -e
cd /c/desarollo/innova/sst-auditor-agent-pro-backend
SOURCE=".openspec-cli/.review-output.md"
if [ ! -f "$SOURCE" ]; then
  echo "Missing $SOURCE" >&2
  exit 1
fi
TEMP=$(mktemp)
{
  echo "<!-- os-review: OpenSpec AI Code Review -->"
  echo "> **AI Code Review** generated by OpenSpec CLI"
  echo "> Stack: \`python-fastapi\` | Reviewer: Copilot via os-review"
  echo ""
  echo "---"
  echo ""
  cat "$SOURCE"
} > "$TEMP"
gh pr comment 36 --body-file "$TEMP"
gh pr review 36 --approve --body "Approved by OpenSpec AI review. See comment above for details." \
  || gh pr review 36 --comment --body "OpenSpec: veredicto APPROVE (GitHub puede bloquear approve en PR propio). Ver comentario de review arriba."
rm -f "$TEMP"
mv -f "$SOURCE" "${SOURCE}.applied"
gh pr view 36 --json url -q .url
